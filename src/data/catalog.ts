export function generateSlug(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)+/g, '');
}

export function generateSku(category: string, id: string): string {
  let catCode = 'PROD';
  const c = (category || '').toLowerCase();
  if (c.includes('spray')) catCode = 'SPRAY';
  else if (c.includes('tablet')) catCode = 'TABLET';
  else if (c.includes('honey')) catCode = 'HONEY';
  else if (c.includes('cream')) catCode = 'CREAM';
  else if (c.includes('condom')) catCode = 'CONDOM';
  else if (c.includes('oil') || c.includes('serum')) catCode = 'OIL';
  else if (c.includes('herbal')) catCode = 'HERBAL';
  else if (c.includes('beauty')) catCode = 'BEAUTY';
  else {
    catCode = category.replace(/[^a-zA-Z]/g, '').substring(0, 5).toUpperCase() || 'PROD';
  }
  const num = id.replace(/[^0-9]/g, '').slice(-2) || '01';
  return `DW-${catCode}-${num.padStart(2, '0')}`;
}

